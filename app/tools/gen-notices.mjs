// Generates the open-source licence notices (SPECS §14.3): every production
// dependency of the app (npm), plus native code compiled in (Arasan, Syzygy).
//
//   node tools/gen-notices.mjs
//
// Writes src/licenses.json (for the in-app Licences screen; identical licence
// texts are stored once) and ../THIRD_PARTY_NOTICES.md. Re-run after changing
// dependencies.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const APP = new URL('..', import.meta.url).pathname;
const ROOT = join(APP, '..');

const paths = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: APP, encoding: 'utf8', maxBuffer: 64 << 20 })
  .split('\n')
  .filter((p) => p && p !== APP.replace(/\/$/, ''));

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
}

const byName = new Map();
for (const dir of paths) {
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  } catch {
    continue;
  }
  if (!pkg.name || pkg.private) continue;
  const key = `${pkg.name}@${pkg.version}`;
  if (byName.has(key)) continue;
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  const text = licenseText(dir) ?? `${license} licence; see ${pkg.repository?.url ?? pkg.homepage ?? 'the package'} (no licence file in the package).`;
  byName.set(key, { name: pkg.name, version: pkg.version, license, text });
}

// Native code compiled into the app, not from npm.
const nativeEntries = [
  { name: 'Arasan chess engine (incl. NNUE network)', version: '26.1', license: 'MIT', dir: '../native/arasan' },
  { name: 'Syzygy tablebase probing (Fathom)', version: 'Arasan bundled', license: 'MIT', dir: '../native/arasan/src/syzygy' },
];
for (const n of nativeEntries) {
  byName.set(n.name, { name: n.name, version: n.version, license: n.license, text: licenseText(join(APP, n.dir)) });
}

const list = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
const texts = [];
const index = new Map();
const packages = list.map(({ name, version, license, text }) => {
  if (!index.has(text)) {
    index.set(text, texts.length);
    texts.push(text);
  }
  return { n: name, v: version, l: license, t: index.get(text) };
});

writeFileSync(join(APP, 'src/licenses.json'), JSON.stringify({ packages, texts }));
writeFileSync(
  join(ROOT, 'THIRD_PARTY_NOTICES.md'),
  `# Third-party notices\n\nPeermate includes the following open-source software. Generated by \`app/tools/gen-notices.mjs\`.\n\n` +
    list.map((p) => `## ${p.name} ${p.version} (${p.license})\n\n\`\`\`\n${p.text}\n\`\`\`\n`).join('\n'),
);
const unknown = list.filter((p) => !p.license || p.license === 'UNKNOWN').map((p) => p.name);
const licenses = {};
for (const p of list) licenses[p.license] = (licenses[p.license] ?? 0) + 1;
console.log(`${list.length} components, ${texts.length} distinct licence texts`);
console.log('by licence:', JSON.stringify(licenses));
if (unknown.length) console.log('UNKNOWN licence:', unknown.join(', '));
